package httpclient

import (
	"math/rand"
	"sync"
	"time"
)

// uaPool provides thread-safe random User-Agent rotation.
type uaPool struct {
	mu   sync.Mutex
	rng  *rand.Rand
	list []string
}

// Pool is the global UA pool instance.
var Pool = &uaPool{
	rng:  rand.New(rand.NewSource(time.Now().UnixNano())),
	list: uaList,
}

// GetRandom returns a random User-Agent string from the pool.
// Thread-safe for concurrent access.
func (p *uaPool) GetRandom() string {
	p.mu.Lock()
	defer p.mu.Unlock()
	return p.list[p.rng.Intn(len(p.list))]
}

